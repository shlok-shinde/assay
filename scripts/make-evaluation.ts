// pnpm eval:report writes docs/EVALUATION.md from the result files, so no number in it is typed by hand. Run the evaluations
// first: pnpm eval, pnpm eval:ai, pnpm eval:visual, pnpm eval:people.
import { existsSync, readFileSync, writeFileSync } from "node:fs";

const read = <T>(file: string): T | null => (existsSync(file) ? (JSON.parse(readFileSync(file, "utf8")) as T) : null);
const at = (iso?: string) => (iso ? iso.slice(0, 10) : "not run");
const num = (v: number | null | undefined) => (v === null || v === undefined ? "n/a" : v.toFixed(3));
const title = (s: string) => s[0].toUpperCase() + s.slice(1);

interface Row {
  category?: string;
  name?: string;
  tp: number;
  fp: number;
  fn: number;
  precision: number | null;
  recall: number | null;
}
interface Scored {
  rows: Row[];
  overall: Omit<Row, "category" | "name">;
}

function table(s: Scored) {
  const lines = ["| Category | True pos. | False pos. | False neg. | Precision | Recall |", "|---|---:|---:|---:|---:|---:|"];
  for (const r of s.rows) lines.push(`| ${title(r.category ?? r.name ?? "")} | ${r.tp} | ${r.fp} | ${r.fn} | ${num(r.precision)} | ${num(r.recall)} |`);
  lines.push(`| **Overall** | **${s.overall.tp}** | **${s.overall.fp}** | **${s.overall.fn}** | **${num(s.overall.precision)}** | **${num(s.overall.recall)}** |`);
  return lines.join("\n");
}

const totals = (rows: Row[]): Scored["overall"] => {
  const t = rows.reduce((a, r) => ({ tp: a.tp + r.tp, fp: a.fp + r.fp, fn: a.fn + r.fn }), { tp: 0, fp: 0, fn: 0 });
  const ratio = (n: number, d: number) => (d ? Math.round((n / d) * 1000) / 1000 : null);
  return { ...t, precision: ratio(t.tp, t.tp + t.fp), recall: ratio(t.tp, t.tp + t.fn) };
};

const rules = read<{ ranAt: string; factsAsOf: string; drafts: number; rows: Row[]; overall: { precision: number; recall: number }; heldout: { rows: Row[] }; misses: string[] }>("docs/eval-results.json");
const first = read<{ ranAt: string; rows: Row[]; misses: string[] }>("docs/eval-first-run-104.json");
const ai = read<{ ranAt: string; all: { drafts: number; answered: number; models: string[]; rulesOnly: Scored; aiOnly: Scored; combined: Scored }; heldout: { answered: number; drafts: number; aiOnly: Scored; combined: Scored } }>("docs/eval-ai-results.json");
const visual = read<{ ranAt: string; truth: string; categories: Row[]; rules: Row[]; logosFound: { found: number; of: number; note: string }; disagreements: string[] }>("docs/eval-visual-results.json");
const people = read<{ ranAt: string; claim: string; people: number; draftsLabelled: number; draftsInSet: number; draftsWithTwoOrMore: number; ruleDecisions: number; unresolvedAndLeftOut: number; agreementBetweenPeople: { cohensKappa: number | null; decisionPairs: number }; agreementWithBuilderLabels: { cohensKappa: number | null; decisions: number }; aiCoverage: { answered: number; of: number }; rulesOnly: Scored; rulesOnlyHeldout: Scored; combined: Scored }>("docs/eval-people-results.json");
const perf = read<{ ranAt: string; throttle: number; steps: Record<string, number>; landingFps: number; scrollFps: number; worstBlockMs: number; blocksOver300ms: unknown[] }>("docs/perf-results.json");

const out: string[] = [
  "# Evaluation",
  "",
  "Generated by `pnpm eval:report` from the result files in `docs/`. Every number says whose labels it is scored against.",
  "",
  "## Labels from people other than the builder",
  "",
];
if (people?.draftsLabelled) {
  out.push(
    `**${people.claim}**`,
    "",
    `Scored on ${at(people.ranAt)} from the raw answers in \`golden/labels/\`. People: ${people.people}. Drafts labelled: ${people.draftsLabelled} of ${people.draftsInSet}. Drafts with two or more labels: ${people.draftsWithTwoOrMore}.`,
    "",
    `Agreement between people (Cohen's kappa): ${num(people.agreementBetweenPeople.cohensKappa)} over ${people.agreementBetweenPeople.decisionPairs} paired decisions. Agreement with the builder's labels: ${num(people.agreementWithBuilderLabels.cohensKappa)}. The builder settles no disagreement: ${people.unresolvedAndLeftOut} of ${people.ruleDecisions} rule decisions were left out because people split evenly.`,
    "",
    "Rule checks against these labels:",
    "",
    table(people.rulesOnly),
    "",
    `Rule checks and AI together, on the ${people.aiCoverage.answered} labelled drafts of ${people.aiCoverage.of} the AI answered:`,
    "",
    table(people.combined),
  );
} else {
  out.push("**Not delivered so far: no drafts have labels from people other than the builder.** Everything below is scored against the builder's own labels, so it measures the engine against its specification, not against independent judgment.");
}
out.push("", "## Rule checks, against the builder's labels", "");
if (rules) {
  out.push(
    `${rules.drafts} fictional drafts in \`golden/drafts.ts\`, written by the builder with AI assistance, with labels written from the rule texts before each draft met the engine. Run on ${at(rules.ranAt)}, facts as of ${rules.factsAsOf}. No AI involved.`,
    "",
    table({ rows: rules.rows, overall: totals(rules.rows) }),
    "",
    "On the kept-back half, which was not used to tune anything:",
    "",
    table({ rows: rules.heldout.rows, overall: totals(rules.heldout.rows) }),
    "",
    "Disagreements left in, not tuned away:",
    "",
    ...rules.misses.map((m) => `- ${m}`),
  );
  if (first) out.push("", `The first run on this set (${at(first.ranAt)}) stays on record in \`docs/eval-first-run-104.json\`, whatever later work does to the numbers: ${totals(first.rows).tp} true positives, ${totals(first.rows).fp} false positives, ${totals(first.rows).fn} false negatives.`);
}
out.push("", "## AI judgment, against the builder's labels", "");
if (ai?.all.answered) {
  out.push(
    `Recorded on ${at(ai.ranAt)} through the deployed route. Coverage: the AI answered ${ai.all.answered} of ${ai.all.drafts} drafts. Models: ${ai.all.models.join(", ")}. \`pnpm eval:ai\` replays the recording without calling anything.`,
    "",
    "AI only, on the rules the AI is asked to judge:",
    "",
    table(ai.all.aiOnly),
    "",
    `Rule checks and AI together, on the drafts the AI answered:`,
    "",
    table(ai.all.combined),
    "",
    `On the kept-back half (${ai.heldout.answered} of ${ai.heldout.drafts} answered), AI only:`,
    "",
    table(ai.heldout.aiOnly),
  );
} else {
  out.push("Not measured yet: no AI answers are on record, so there are no AI-judgment scores.");
}
out.push("", "## Visual checks, against what was drawn", "");
if (visual) {
  out.push(
    `${visual.truth} Run on ${at(visual.ranAt)} with real OCR and no logo marked by hand.`,
    "",
    table({ rows: visual.rules, overall: totals(visual.rules) }),
    "",
    `Logos found: ${visual.logosFound.found} of ${visual.logosFound.of}. ${visual.logosFound.note}`,
    "",
    ...(visual.disagreements.length ? ["Disagreements:", "", ...visual.disagreements.map((d) => `- ${d}`)] : ["No disagreements on this set."]),
  );
} else out.push("Not measured yet.");
out.push(
  "",
  "## Fix acceptance rate",
  "",
  "Measured inside the app, per rule, on Guideline Health: accepted or lightly edited (30% or less changed) over everything decided, with the last decision on a finding winning, so an Undo counts. Seeded history and automated browsers are excluded. It lives in each browser's workspace, so a number only exists where people have used the app; any figure reported for this project says how many decisions it comes from and whose they were.",
  "",
  "## Speed",
  "",
);
if (perf) {
  out.push(`\`pnpm perf\` on ${at(perf.ranAt)}, Chromium with the CPU slowed ${perf.throttle} times, AI off. Landing ${perf.landingFps} fps, ${perf.scrollFps} fps while scrolling. Longest block ${perf.worstBlockMs} ms; blocks over 300 ms: ${perf.blocksOver300ms.length}.`, "", "| Step | Time |", "|---|---:|", ...Object.entries(perf.steps).map(([k, v]) => `| ${title(k)} | ${(v / 1000).toFixed(1)} s |`));
} else out.push("Not measured yet.");
out.push("", "These are machine timings. They show how long the app makes a person wait, not how long a person takes.", "");
writeFileSync("docs/EVALUATION.md", out.join("\n"));
console.log("Wrote docs/EVALUATION.md");
