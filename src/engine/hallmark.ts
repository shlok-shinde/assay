// Hallmarks: a hash-chained record written when content is approved.
// Each one includes the previous Hallmark's hash, so editing any old record
// breaks every hash after it.
import type { Hallmark, HallmarkBody } from "@/lib/types";
import { hashJson, sha256Hex } from "./hash";

export const GENESIS = "0".repeat(64);

export async function sealHallmark(body: HallmarkBody, id: string, seq: number): Promise<Hallmark> {
  const hash = await hashJson(body);
  return { ...body, id, seq, hash };
}

export interface HallmarkVerification {
  ok: boolean;
  contentMatches: boolean;
  bodyMatches: boolean;
  chainMatches: boolean;
  recomputed: string;
}

export async function verifyHallmark(h: Hallmark, content: string, previous?: Hallmark): Promise<HallmarkVerification> {
  // Rebuild the exact body that was hashed: every field except id, seq and hash.
  const body: HallmarkBody = {
    submissionId: h.submissionId,
    title: h.title,
    versionId: h.versionId,
    versionN: h.versionN,
    contentHash: h.contentHash,
    rulebookVersion: h.rulebookVersion,
    rulebookHash: h.rulebookHash,
    findings: h.findings,
    approvals: h.approvals,
    ai: h.ai,
    prevHash: h.prevHash,
    issuedAt: h.issuedAt,
  };
  const recomputed = await hashJson(body);
  const contentMatches = (await sha256Hex(content)) === h.contentHash;
  const bodyMatches = recomputed === h.hash;
  const chainMatches = previous ? previous.hash === h.prevHash : h.prevHash === GENESIS;
  return { ok: contentMatches && bodyMatches && chainMatches, contentMatches, bodyMatches, chainMatches, recomputed };
}

export function hallmarkMarkdown(h: Hallmark, content: string): string {
  const lines = [
    `# Hallmark #${h.seq}: ${h.title}`,
    "",
    `- Issued: ${h.issuedAt}`,
    `- Version: v${h.versionN} (${h.versionId})`,
    `- Content SHA-256: \`${h.contentHash}\``,
    `- Rulebook: v${h.rulebookVersion} (SHA-256 \`${h.rulebookHash}\`)`,
    `- Previous Hallmark: \`${h.prevHash}\``,
    `- This Hallmark: \`${h.hash}\``,
    `- AI: ${h.ai.mode}; models ${h.ai.models.join(", ") || "none"}; ${h.ai.calls} call(s); ${h.ai.redactions} redaction(s)`,
    "",
    "## Approvals",
    ...h.approvals.map((a) => `- ${a.role}: ${a.by}, ${a.decision}, ${a.at}`),
    "",
    "## Findings and how each was resolved",
    ...h.findings.map((f) => `- ${f.ruleId} (${f.severity}): ${f.status}${f.reason ? `, “${f.reason}”` : ""}${f.by ? `, by ${f.by}` : ""}`),
    "",
    "## Approved content",
    "",
    "```",
    content,
    "```",
    "",
    "Generated by Assay. Recompute the SHA-256 of the content above to check it matches.",
  ];
  return lines.join("\n");
}
