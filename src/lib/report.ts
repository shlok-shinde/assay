// A draft's record for someone who doesn't use Assay: what was checked, what was found, who decided what.
// Everything here is read from the store; nothing is summarised by AI.
import type { Approval, Check, Comment, Finding, Hallmark, Rule, Submission, Version } from "./types";

export interface DraftRecord {
  sub: Submission;
  versions: Version[];
  check?: Check;
  findings: Finding[];
  rules: Rule[];
  approvals: Approval[];
  comments: Comment[];
  hallmark?: Hallmark;
  /** When this record was made. */
  at: string;
}

const STATUS: Record<Finding["status"], string> = {
  open: "Open",
  accepted: "Fix accepted",
  edited: "Fix edited",
  dismissed: "Dismissed",
  contested: "Contested",
  sent_to_compliance: "With Compliance",
  compliance_approved: "Approved by Compliance",
  reopened: "Sent back",
  waived: "Open when approved (waived)",
  superseded: "Replaced by a later version",
};

const CHECK_MODE: Record<Check["mode"], string> = { "rules+ai": "Rule checks and AI judgment", "rules-only": "Rule checks only", confidential: "Rule checks only (Confidential mode)" };
const oneLine = (s: string) => s.replace(/\s+/g, " ").trim();
const cell = (s: string) => oneLine(s).replace(/\|/g, "\\|");

export function draftReportMarkdown(r: DraftRecord): string {
  const version = r.versions[r.versions.length - 1];
  const severity = { high: 0, medium: 1, low: 2 };
  const findings = [...r.findings].sort((a, b) => severity[a.severity] - severity[b.severity]);
  const rule = (id: string) => r.rules.find((x) => x.id === id);
  const out = [
    `# ${r.sub.title}`,
    "",
    `- Channel: ${r.sub.channel}`,
    `- Audience: ${r.sub.audience || "not given"}`,
    `- Status: ${r.sub.status.replace("_", " ")}`,
    `- Version: v${version?.n ?? "?"} of ${r.versions.length}`,
    `- Rulebook: v${r.check?.rulebookVersion ?? r.sub.rulebookVersion}`,
    `- Checked with: ${r.check ? CHECK_MODE[r.check.mode] : "not checked yet"}`,
    `- Report made: ${r.at}`,
  ];
  if (r.check?.banner) out.push("", `Note on this check: ${r.check.banner}`);
  out.push("", "## Intent Card", "", `- Goal: ${r.sub.intent.goal || "not given"}`, `- Key message: ${r.sub.intent.keyMessage || "not given"}`, `- Call to action: ${r.sub.intent.cta || "not given"}`);
  out.push("", `## Findings (${findings.length})`, "");
  if (findings.length) {
    out.push("| Severity | Rule | Words | Why | Where it comes from | Decision |", "|---|---|---|---|---|---|");
    for (const f of findings) {
      const source = rule(f.ruleId)?.source;
      const where = source?.page ? `${source.doc}, p.${source.page}${source.section ? ` ${source.section}` : ""}` : "Rule record";
      const decided = [STATUS[f.status], f.resolution?.by && `by ${f.resolution.by}`, f.resolution?.reason && `(“${f.resolution.reason}”)`, f.intentOverride && `intent override: “${f.intentOverride.reason}”`].filter(Boolean).join(" ");
      out.push(`| ${f.severity} | ${f.ruleId}: ${cell(f.title)} | ${cell(f.quote)} | ${cell(f.reason)} | ${cell(where)} | ${cell(decided)} |`);
    }
  } else out.push("None on this version.");
  if (r.check?.claims.length) {
    out.push("", "## Claims checked against the Claim Ledger", "", "| Claim | Result | Detail |", "|---|---|---|");
    for (const c of r.check.claims) out.push(`| ${cell(c.text)} | ${c.status} | ${cell(c.detail)} |`);
  }
  if (r.versions.length > 1) {
    out.push("", "## Versions", "");
    for (const v of r.versions) out.push(`- v${v.n}, ${v.createdAt}, ${v.author}: ${v.note || v.source.kind}${v.intentCheck ? `. Intent: ${v.intentCheck.verdict ?? (v.intentCheck.kept ? "kept" : "review")}` : ""}`);
  }
  if (r.approvals.length) {
    out.push("", "## Decisions", "");
    for (const a of r.approvals) out.push(`- ${a.at}, ${a.by} (${a.role}): ${a.decision.replace("_", " ")}${a.note ? `, “${oneLine(a.note)}”` : ""}`);
  }
  if (r.comments.length) {
    out.push("", "## Comments", "");
    for (const c of r.comments) out.push(`- ${c.at}, ${c.author} (${c.role}): ${oneLine(c.text)}`);
  }
  if (r.hallmark) out.push("", "## Hallmark", "", `#${r.hallmark.seq}, issued ${r.hallmark.issuedAt}.`, `- Content SHA-256: \`${r.hallmark.contentHash}\``, `- Hallmark SHA-256: \`${r.hallmark.hash}\``);
  out.push("", "## The draft", "", "```", version?.text || "(no text)", "```");
  if (version?.image) out.push("", `Creative: ${version.image.fileName}, ${version.image.width} x ${version.image.height} px. Alt text: ${version.image.alt || "none"}.`);
  out.push("", "Generated by Assay from this workspace's records.");
  return out.join("\n");
}
