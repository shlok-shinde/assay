import { describe, expect, it } from "vitest";
import { inlineParts, parseMarkdown } from "./markdown";

describe("The report reader", () => {
  it("reads headings, lists, tables, code and paragraphs, in order", () => {
    const blocks = parseMarkdown(["# Title", "", "- Channel: email", "- Status: checked", "", "Note on this check: one", "", "## Findings (1)", "", "| Severity | Rule |", "|---|---|", "| high | CLAIM-01: A \\| B |", "", "```", "line one", "", "line two", "```", "", "Generated by Assay."].join("\n"));
    expect(blocks).toEqual([
      { kind: "heading", level: 1, text: "Title" },
      { kind: "list", items: ["Channel: email", "Status: checked"] },
      { kind: "paragraph", text: "Note on this check: one" },
      { kind: "heading", level: 2, text: "Findings (1)" },
      { kind: "table", head: ["Severity", "Rule"], rows: [["high", "CLAIM-01: A | B"]] },
      { kind: "code", text: "line one\n\nline two" },
      { kind: "paragraph", text: "Generated by Assay." },
    ]);
  });

  it("keeps everything as text: markup in a draft stays words", () => {
    const blocks = parseMarkdown(["```", "<script>alert(1)</script> # not a heading", "```", "", "<img src=x onerror=alert(1)>", "", "| a |", "|---|", "| <b>x</b> |"].join("\n"));
    expect(blocks[0]).toEqual({ kind: "code", text: "<script>alert(1)</script> # not a heading" });
    expect(blocks[1]).toEqual({ kind: "paragraph", text: "<img src=x onerror=alert(1)>" });
    expect(blocks[2]).toEqual({ kind: "table", head: ["a"], rows: [["<b>x</b>"]] });
  });

  it("always moves on, even for a stray bar or an unclosed fence", () => {
    expect(parseMarkdown("| not a table")).toEqual([{ kind: "paragraph", text: "| not a table" }]);
    expect(parseMarkdown("```\nopen")).toEqual([{ kind: "code", text: "open" }]);
    expect(parseMarkdown("")).toEqual([]);
  });

  it("picks out inline code and nothing else", () => {
    expect(inlineParts("Content SHA-256: `abc123` ok")).toEqual([
      { code: false, text: "Content SHA-256: " },
      { code: true, text: "abc123" },
      { code: false, text: " ok" },
    ]);
    expect(inlineParts("no code, **not bold**")).toEqual([{ code: false, text: "no code, **not bold**" }]);
  });
});
